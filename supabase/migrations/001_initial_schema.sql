-- Directory schema used by backend/services/privateStore.js.
-- Patient records are intentionally not stored in public Postgres tables.
-- They remain encrypted in the private lks-clinical-vault Storage bucket and
-- are accessed by server handlers using the service-role key after staff auth.
-- Do not add anon/authenticated policies to storage.objects for this bucket.

begin;

create table public.lks_hospital (
  id integer primary key check (id = 1),
  is_approved boolean not null default false,
  name text not null check (length(btrim(name)) > 0),
  address text not null check (length(btrim(address)) > 0),
  locality text not null check (length(btrim(locality)) > 0),
  city text not null check (length(btrim(city)) > 0),
  maps_url text not null check (length(btrim(maps_url)) > 0),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  phone text,
  email text,
  hours text,
  introduction text not null check (length(btrim(introduction)) > 0),
  about text not null check (length(btrim(about)) > 0),
  bed_count integer not null check (bed_count >= 0),
  verified_on date not null,
  sources jsonb not null check (jsonb_typeof(sources) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint lks_hospital_email_format check (email is null or email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
);

create table public.lks_departments (
  id integer generated by default as identity primary key,
  is_approved boolean not null default false,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (length(btrim(name)) > 0),
  icon text not null check (length(btrim(icon)) > 0),
  description text not null check (length(btrim(description)) > 0),
  services jsonb not null check (jsonb_typeof(services) = 'array'),
  source_url text not null check (length(btrim(source_url)) > 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.lks_doctors (
  id integer generated by default as identity primary key,
  is_approved boolean not null default false,
  name text not null check (length(btrim(name)) > 0),
  qualification text not null check (length(btrim(qualification)) > 0),
  specialty text not null check (length(btrim(specialty)) > 0),
  experience integer check (experience is null or experience >= 0),
  bio text not null check (length(btrim(bio)) > 0),
  department_id integer not null references public.lks_departments(id) on update cascade on delete restrict,
  source_url text not null check (length(btrim(source_url)) > 0),
  initials text not null check (length(btrim(initials)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index lks_departments_sort_order_idx
  on public.lks_departments (sort_order, id);
create index lks_doctors_department_id_idx
  on public.lks_doctors (department_id, id);

create function public.lks_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := pg_catalog.now();
  return new;
end;
$$;

create trigger lks_hospital_set_updated_at
  before update on public.lks_hospital
  for each row execute function public.lks_set_updated_at();
create trigger lks_departments_set_updated_at
  before update on public.lks_departments
  for each row execute function public.lks_set_updated_at();
create trigger lks_doctors_set_updated_at
  before update on public.lks_doctors
  for each row execute function public.lks_set_updated_at();

alter table public.lks_hospital enable row level security;
alter table public.lks_departments enable row level security;
alter table public.lks_doctors enable row level security;

-- Public directory rows contain only publishable information. No client may
-- write these rows; privileged maintenance uses the server-side service role.
revoke all on table public.lks_hospital, public.lks_departments, public.lks_doctors
  from public, anon, authenticated;
grant select on table public.lks_hospital, public.lks_departments, public.lks_doctors
  to anon, authenticated;
grant select, insert, update, delete on table public.lks_hospital, public.lks_departments, public.lks_doctors
  to service_role;
grant usage, select on sequence public.lks_departments_id_seq, public.lks_doctors_id_seq
  to service_role;

create policy "Public can read hospital directory"
  on public.lks_hospital for select to anon, authenticated using (is_approved);
create policy "Public can read departments"
  on public.lks_departments for select to anon, authenticated using (is_approved);
create policy "Public can read doctors"
  on public.lks_doctors for select to anon, authenticated using (
    is_approved and exists (
      select 1
      from public.lks_departments as department
      where department.id = lks_doctors.department_id
        and department.is_approved
    )
  );

-- Make the new relations visible to Supabase PostgREST immediately.
notify pgrst, 'reload schema';

commit;
